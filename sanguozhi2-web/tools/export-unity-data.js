// FNV-1a 32 位，见文件头注释
class Hash {
  constructor() { this.h = 0x811c9dc5; this.n = 0; }
  bytes(b) { let h = this.h; for (let i = 0; i < b.length; i++) { h ^= b[i]; h = Math.imul(h, 0x01000193) >>> 0; } this.h = h; }
  S(s) { this.n++; if (s === null || s === undefined) { this.bytes([1, 0]); return; } this.bytes(Buffer.from(String(s), 'utf8')); this.bytes([0]); }
  I(v) { if (v === null || v === undefined) this.S(null); else this.S(String(v)); }
  N(v) { this.S(String(Math.floor(Math.fround(v) * 1e4 + 0.5))); }
  NA(a) { this.I(a.length); for (const v of a) this.N(v); }
  hex() { return '0x' + (this.h >>> 0).toString(16).padStart(8, '0'); }
}

