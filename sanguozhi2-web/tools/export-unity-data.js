function csStr(s) {
  if (s === null || s === undefined) return 'null';
  let o = '"';
  for (const ch of String(s)) {
    const c = ch.codePointAt(0);
    if (ch === '\\') o += '\\\\';
    else if (ch === '"') o += '\\"';
    else if (ch === '\n') o += '\\n';
    else if (ch === '\r') o += '\\r';
    else if (ch === '\t') o += '\\t';
    else if (c < 0x20 || c === 0x7f || c === 0x85 || c === 0x2028 || c === 0x2029) o += '\\u' + c.toString(16).padStart(4, '0');
    else o += ch;
  }
  return o + '"';
}
function csFloat(v) {
  if (typeof v !== 'number' || !isFinite(v)) throw new Error('不是有限数值：' + v);
  const s = String(v);
  return (s === '-0' ? '0' : s) + 'f';
}
function csInt(v) {
  if (!Number.isInteger(v)) throw new Error('不是整数：' + v);
  return String(v);
}
function csIntN(v) { return v === null || v === undefined ? 'null' : csInt(v); }
