function fmt6(v) { return (Math.round(v * 1e6) / 1e6).toFixed(6); }
function exportRefs() {
  const S = SG.Specials, W = SG.Scenarios.world;
  const one = sp => [sp.gen, sp.auto ? 'auto' : 'hand', sp.name, sp.kind, sp.stat, S.signature(sp), sp.color, sp.fx, sp.cry || '', sp.desc]
    .map(s => String(s).replace(/[\t\n]/g, ' ')).join('\t');
  const L = ['# 自动生成，勿手改（sanguozhi2-web/tools/export-unity-data.js）。SG.Specials.of(gen) 的补全结果，按下列顺序依次调用（兜底生成有去重状态，顺序有关）。',
    '# 每行以制表符分隔：武将 武力 智力 政治 文化 => 武将 hand/auto 招式名 机制 能力 签名 主色 特效 台词 说明'];
  // 世界剧本全部武将（前 162 名即经典剧本）
  for (const l of W.Generals) {
    const p = l.split('|');
    const g = { name: p[0], war: +p[1], intel: +p[2], pol: +p[3], culture: p[9] || 'han' };
    L.push([g.name, g.war, g.intel, g.pol, g.culture, '=>'].join('\t') + '\t' + one(S.of(g)));
  }
  // 没有手写条目的武将：走兜底生成器（确定性的假名单，覆盖各种能力倾向与文化）
  const CULT = ['han', 'nanman', 'wa', 'yi', 'korea', 'steppe', 'seasia', 'tarim', 'kushan', 'persia', 'arab', 'roman', 'celt', 'german', 'sarmatian'];
  const r = SG.SeededRandom(20261007);
  const SUR = '甲乙丙丁戊己庚辛壬癸子丑寅卯辰巳午未申酉戌亥';
  let made = 0;
  for (let i = 0; made < 72 && i < 500; i++) {
    const name = '无名' + SUR[i % SUR.length] + SUR[(i * 7 + 3) % SUR.length] + (i >= SUR.length ? String(i) : '');
    if (SG.SpecialsData.has(name)) continue;
    const style = i % 4;
    const hi = 60 + r.next(41), lo = 10 + r.next(50), mid = 30 + r.next(60);
    const war = style === 0 ? hi : style === 1 ? lo : style === 2 ? hi - r.next(9) : mid;
    const intel = style === 0 ? lo : style === 1 ? hi : style === 2 ? hi - r.next(9) : lo;
    const pol = style === 3 ? hi : mid;
    const g = { name, war, intel, pol, culture: CULT[i % CULT.length] };
    L.push([g.name, g.war, g.intel, g.pol, g.culture, '=>'].join('\t') + '\t' + one(S.of(g)));
    made++;
  }
  emit(path.join(REF_DIR, 'specials-ref.txt'), L.join('\n') + '\n');

  const P = ['# 自动生成，勿手改（sanguozhi2-web/tools/export-unity-data.js）。SG.project / SG.unproject 的参考结果（6 位小数）。',
    '# project 经度 纬度 => x y ； unproject x y => 经度 纬度 ； world 范围 ； region 键 xMin yMin xMax yMax cx cy'];
  const lons = [], lats = [];
  for (let lo = -20; lo <= 160; lo += 3.7) lons.push(Math.round(lo * 100) / 100);
  for (const v of [-10, 0, 24, 44, 60, 62, 74, 88, 97, 100, 126, 131, 138, 146]) lons.push(v);
  for (let la = -14; la <= 84; la += 4.3) lats.push(Math.round(la * 100) / 100);
  for (const v of [-10, 0, 18, 23, 30, 42, 50, 60, 80]) lats.push(v);
  for (const lo of lons) for (const la of lats) { const p = SG.project(lo, la); P.push(`project ${lo} ${la} => ${fmt6(p.x)} ${fmt6(p.y)}`); }
  for (let x = -260; x <= 260; x += 23) for (let y = -150; y <= 240; y += 19) { const q = SG.unproject(x, y); P.push(`unproject ${x} ${y} => ${fmt6(q.lon)} ${fmt6(q.lat)}`); }
  const Wd = SG.World;
  P.push(`world ${fmt6(Wd.x0)} ${fmt6(Wd.y0)} ${fmt6(Wd.x1)} ${fmt6(Wd.y1)} ${fmt6(Wd.W)} ${fmt6(Wd.H)}`);
  for (const k of Object.keys(Wd.regions)) { const g = Wd.regions[k]; P.push(`region ${k} ${[g.xMin, g.yMin, g.xMax, g.yMax, g.cx, g.cy].map(fmt6).join(' ')}`); }
  emit(path.join(REF_DIR, 'project-ref.txt'), P.join('\n') + '\n');
}

