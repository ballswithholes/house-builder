# tools/voice-build/pack.py — step 5 of the offline voice pipeline (AUDIO-V4 §B7.1, §B7.2)
# Encodes every clip that passed qa.py with libopus 16 kbps mono (-application voip, 24 kHz; each clip a complete Ogg Opus file)
# and the MP3 fallback (LAME 32 kbps mono, 22.05 kHz), and writes the packs as classic scripts (file:// cannot fetch):
#   voice/<lingua>-<voice>.js       SG.VoicePacks.add({ id, lingua, voice, model, codec: 'opus', clips: { cue: [[offset, length, ms, rmsDb] | null, …] },
#                                                       sig: { ruler: [...] } }, '<base64 of the concatenated clips>')
#   voice/mp3/<lingua>-<voice>.js   the same with codec 'mp3' (downloaded only when the Opus probe fails, e.g. older Safari)
#   voice/manifest.js               SG.VoiceManifest: packs, sizes, sha1, licences, failed linguas, the codec probe clips
#   voice/LICENSES.md               every model and its licence
# Usage: python3 -I tools/voice-build/pack.py <wav dir> <repo root> [--no-mp3]
import sys, os, json, base64, hashlib, subprocess, tempfile, wave, math, time
import numpy as np

wavdir, root = sys.argv[1], sys.argv[2]
NO_MP3 = '--no-mp3' in sys.argv
synth = json.load(open(os.path.join(wavdir, 'synth.json'), encoding='utf-8'))
qa = json.load(open(os.path.join(wavdir, 'qa.json'), encoding='utf-8'))
ok = { (c['pack'], c['id']): c for c in qa['clips'] }
failed_linguas = [lg for lg, s in qa['linguas'].items() if s['failed']]
out_dir = os.path.join(root, 'voice'); mp3_dir = os.path.join(out_dir, 'mp3')
os.makedirs(mp3_dir, exist_ok=True)

def enc(fn, codec):
    args = ['ffmpeg', '-loglevel', 'error', '-i', fn, '-ac', '1']
    if codec == 'opus': args += ['-ar', '24000', '-c:a', 'libopus', '-b:a', '16k', '-application', 'voip', '-f', 'ogg', '-map_metadata', '-1', 'pipe:1']
    else: args += ['-ar', '22050', '-c:a', 'libmp3lame', '-b:a', '32k', '-f', 'mp3', '-map_metadata', '-1', '-write_xing', '0', 'pipe:1']
    return subprocess.run(args, check=True, capture_output=True).stdout

packs = {}
for r in synth:
    if r.get('error'): continue
    q = ok.get((r['pack'], r['id']))
    if not q or not q['ok']: continue
    if r['lingua'] in failed_linguas: continue
    packs.setdefault(r['pack'], []).append(r)

def js_pack(meta, b64):
    return ("'use strict';\n/* generated by tools/voice-build/pack.py — do not edit (AUDIO-V4 §B7.1) */\n(function () {\n"
            "  var W = typeof window !== 'undefined' ? window : globalThis; var SG = W.SG = W.SG || {};\n"
            "  var P = SG.VoicePacks = SG.VoicePacks || { _q: [], add: function (m, d) { this._q.push([m, d]); } };\n"
            "  P.add(" + json.dumps(meta, ensure_ascii=False, separators=(',', ':')) + ",\n'" + b64 + "');\n})();\n")

manifest = { 'version': 1, 'built': time.strftime('%Y-%m-%d'), 'codec': 'opus', 'bitrate': '16k', 'packs': {}, 'failed': failed_linguas,
             'dropped': sorted(c['pack'] + '/' + c['id'] for c in qa['clips'] if not c['ok']) }   # clips the QA gate dropped (the runtime walks the fallback chain)
lic_rows = {}
tot = { 'clips': 0, 'opus': 0, 'mp3': 0, 'sec': 0.0 }
for pid in sorted(packs):
    rs = sorted(packs[pid], key=lambda r: (r['cue'], str(r['variant'])))
    meta = { 'id': pid, 'lingua': rs[0]['lingua'], 'voice': pid.split('-', 1)[1], 'model': rs[0]['model'] + ('#' + str(rs[0]['speaker']) if rs[0].get('speaker') is not None else ''), 'clips': {}, 'sig': {} }
    blobs = { 'opus': bytearray(), 'mp3': bytearray() }
    metas = { 'opus': json.loads(json.dumps(meta)), 'mp3': json.loads(json.dumps(meta)) }
    for r in rs:
        fn = os.path.join(wavdir, r['wav'])
        ms = int(round(r['dur'] * 1000))
        for codec in (('opus',) if NO_MP3 else ('opus', 'mp3')):
            b = enc(fn, codec)
            ent = [len(blobs[codec]), len(b), ms, r['rms_db']]
            blobs[codec] += b
            m = metas[codec]
            if r['cue'] == 'sig': m['sig'][r['variant']] = ent
            else:
                arr = m['clips'].setdefault(r['cue'], [])
                v = int(r['variant'])
                while len(arr) <= v: arr.append(None)
                arr[v] = ent
        tot['clips'] += 1; tot['sec'] += r['dur']
        lic_rows[r['model']] = ok[(r['pack'], r['id'])]['licence']
    for codec in (('opus',) if NO_MP3 else ('opus', 'mp3')):
        m = metas[codec]; m['codec'] = codec; m['sr'] = 24000 if codec == 'opus' else 22050
        b64 = base64.b64encode(bytes(blobs[codec])).decode('ascii')
        txt = js_pack(m, b64)
        fn = os.path.join(out_dir if codec == 'opus' else mp3_dir, pid + '.js')
        open(fn, 'w', encoding='utf-8').write(txt)
        tot[codec] += len(blobs[codec])
        e = manifest['packs'].setdefault(pid, { 'lingua': meta['lingua'], 'voice': meta['voice'], 'model': meta['model'], 'clips': len(rs) })
        if codec == 'opus':
            e.update(file='voice/' + pid + '.js', bytes=len(blobs[codec]), jsBytes=len(txt.encode('utf-8')), sha1=hashlib.sha1(bytes(blobs[codec])).hexdigest()[:12])
        else:
            e.update(mp3='voice/mp3/' + pid + '.js', mp3Bytes=len(blobs[codec]))
    print(f"{pid:12s} {len(rs):4d} clips  opus {len(blobs['opus']) / 1024:7.1f} KB" + ('' if NO_MP3 else f"  mp3 {len(blobs['mp3']) / 1024:7.1f} KB"), flush=True)

# codec probe clips (≈ 0.12 s, 440 Hz): voice.js decodes the Opus one at init and switches to MP3 packs if it fails
with tempfile.TemporaryDirectory() as td:
    fn = os.path.join(td, 'probe.wav'); sr = 24000
    t = np.arange(int(0.12 * sr)) / sr
    a = (0.2 * np.sin(2 * math.pi * 440 * t) * np.minimum(1, np.minimum(t, 0.12 - t) / 0.01)).astype(np.float32)
    with wave.open(fn, 'wb') as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(sr); w.writeframes((a * 32767).astype(np.int16).tobytes())
    manifest['probe'] = { 'opus': base64.b64encode(enc(fn, 'opus')).decode('ascii'), 'mp3': base64.b64encode(enc(fn, 'mp3')).decode('ascii') }
manifest['totals'] = { 'clips': tot['clips'], 'minutes': round(tot['sec'] / 60, 1), 'opusBytes': tot['opus'], 'mp3Bytes': tot['mp3'] }
manifest['licences'] = lic_rows
open(os.path.join(out_dir, 'manifest.js'), 'w', encoding='utf-8').write(
    "'use strict';\n/* generated by tools/voice-build/pack.py — do not edit (AUDIO-V4 §B7.1) */\n(function () {\n"
    "  var W = typeof window !== 'undefined' ? window : globalThis; var SG = W.SG = W.SG || {};\n"
    "  SG.VoiceManifest = " + json.dumps(manifest, ensure_ascii=False, indent=1) + ";\n})();\n")
L = ['# Voice pack licences (generated by tools/voice-build/pack.py)', '',
     'Every clip in `voice/` was rendered offline by the AUDIO-V4 §B7 pipeline (`tools/voice-build/`) from the models below.',
     'Licences marked non-commercial or "see URL" must be checked before distributing the game beyond personal use (AUDIO-V4 open question 1).', '',
     '| model | licence | packs |', '|---|---|---|']
for m, l in sorted(lic_rows.items()):
    L.append(f"| `{m}` | {l} | {', '.join(sorted(p for p, e in manifest['packs'].items() if e['model'].split('#')[0] == m))} |")
L += ['', f"Failed QA (no pack, runtime uses the lingua fallback chain): {', '.join(failed_linguas) or 'none'}.", '',
      f"Totals: {tot['clips']} clips, {tot['sec'] / 60:.1f} min of speech, Opus {tot['opus'] / 1048576:.2f} MB" + ('' if NO_MP3 else f", MP3 fallback {tot['mp3'] / 1048576:.2f} MB") + '.']
open(os.path.join(out_dir, 'LICENSES.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print(f"packs: {len(packs)}, clips {tot['clips']}, {tot['sec'] / 60:.1f} min, opus {tot['opus'] / 1048576:.2f} MB" + ('' if NO_MP3 else f", mp3 {tot['mp3'] / 1048576:.2f} MB") + f"; failed linguas {failed_linguas}")
