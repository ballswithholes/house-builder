#!/usr/bin/env node
'use strict';
/* ==========================================================================
   导出全部乐曲的乐谱数据到 Unity 版（UNITY-V2 §2）
     node tools/export-unity-music.js [输出路径]
   在沙箱里按游戏顺序载入 js/music.js、music-inst.js、music-han.js、music-world.js（不碰 DOM、不编译乐曲），
   把 SG.Music.PIECES 的每首乐曲（记谱字符串、声部、鼓谱、节奏型、段落、曲式……）原样写成规范 JSON，
   生成 ../sanguozhi2-unity/Assets/Sanguo/Scripts/Data/Generated/MusicScores.g.cs：
     MusicScores.Pieces      = { key, 乐曲 JSON, … }（注册顺序；键按 JS 的属性顺序，与 for-in 一致）
     MusicScores.Instruments = { 乐器名, 缺省混音参数 JSON, … }（gain 已含混音校准 CAL；供 C# 测试核对手工移植的乐器表）
     MusicScores.Count / Hash = 乐曲数与校验哈希（FNV-1a 32，见下）；C# 测试据此确认数据完整
   无依赖，Node 14+。乐曲有变时重新运行即可。
   ========================================================================== */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const WEB = path.resolve(__dirname, '..');
const OUT = process.argv[2] || path.resolve(WEB, '../sanguozhi2-unity/Assets/Sanguo/Scripts/Data/Generated/MusicScores.g.cs');

const sandbox = { console, performance: { now: () => Date.now() } };
sandbox.window = sandbox;
vm.createContext(sandbox);
for (const f of ['music.js', 'music-inst.js', 'music-han.js', 'music-world.js']) {
  vm.runInContext(fs.readFileSync(path.join(WEB, 'js', f), 'utf8'), sandbox, { filename: f });
}
const MU = sandbox.SG.Music;
const keys = MU.keys();

// 规范 JSON：键按 JS 属性顺序；数值用 JS 的格式；引擎运行时写入的内部字段（key_ _keyMidi _derived _base droneMidi）不导出
const INTERNAL = { key_: 1, _keyMidi: 1, _derived: 1, _base: 1, droneMidi: 1 };
function canon(v) {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') { if (!isFinite(v)) throw new Error('非有限数值'); return String(v); }
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'string') return JSON.stringify(v);
  if (Array.isArray(v)) return '[' + v.map(canon).join(',') + ']';
  if (typeof v === 'object') {
    const parts = [];
    for (const k of Object.keys(v)) {
      if (v[k] === undefined || typeof v[k] === 'function' || INTERNAL[k]) continue;
      parts.push(JSON.stringify(k) + ':' + canon(v[k]));
    }
    return '{' + parts.join(',') + '}';
  }
  throw new Error('无法导出的值：' + typeof v);
}
// FNV-1a 32（按 UTF-16 码元），对 "key\u0001JSON\u0002" 逐首累计
function fnv(h, s) {
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619) >>> 0; }
  return h >>> 0;
}
const cs = s => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\r/g, '\\r').replace(/\t/g, '\\t') + '"';

let hash = 2166136261 >>> 0;
const lines = [];
for (const k of keys) {
  const j = canon(MU.PIECES[k]);
  JSON.parse(j);
  hash = fnv(hash, k + '\u0001' + j + '\u0002');
  lines.push(`            ${cs(k)},\n            ${cs(j)},`);
}
// 乐器的缺省参数（标量；渲染参数在 JS 闭包里，由 C# 手工移植，测试用采样比对核实）
const instLines = [];
for (const n of Object.keys(MU.INST)) {
  const d = MU.INST[n], o = {};
  for (const a of Object.keys(d)) if (typeof d[a] !== 'function' && a !== 'name') o[a] = d[a];
  instLines.push(`            ${cs(n)}, ${cs(canon(o))},`);
}

const src = `// <auto-generated>
// 自动生成，勿手改：由 sanguozhi2-web/tools/export-unity-music.js 从 js/music-han.js、js/music-world.js 导出。
// 乐曲有变时在 sanguozhi2-web 目录运行 node tools/export-unity-music.js 重新生成。
// 记谱法见 js/music.js 文件头；运行时由 Core/MusicEngine.cs 的 MusicLib 解析编译。
// </auto-generated>
namespace Sanguo.Audio
{
    public static class MusicScores
    {
        public const int Count = ${keys.length};
        public const uint Hash = 0x${hash.toString(16).padStart(8, '0')}u;   // FNV-1a 32 over "key\\u0001JSON\\u0002"
        // key, 乐曲 JSON（键按 JS 属性顺序）
        public static readonly string[] Pieces =
        {
${lines.join('\n')}
        };
        // 乐器名, 缺省混音参数 JSON（gain 含混音校准）
        public static readonly string[] Instruments =
        {
${instLines.join('\n')}
        };
    }
}
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, src);
console.log(`MusicScores.g.cs：${keys.length} 首、乐器 ${instLines.length} 种，hash 0x${hash.toString(16).padStart(8, '0')} → ${path.relative(process.cwd(), OUT)}`);
