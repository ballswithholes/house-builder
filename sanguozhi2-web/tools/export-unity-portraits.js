#!/usr/bin/env node
'use strict';
/* ==========================================================================
   导出头像外貌设定到 Unity 版（UNITY-V2 §2、UNITY-V3 §2）
     node tools/export-unity-portraits.js [输出路径]
     node tools/export-unity-portraits.js --check   只比较：数据改过却没重新导出时退出码 1
   读取 js/portrait-data.js（连同其依赖 core.js、data.js、world-data.js，按游戏的载入顺序），
   把 SG.PortraitData 的全部条目（含世界剧本自动补全的 culture / sex / role / age）原样写成
   ../sanguozhi2-unity/Assets/Sanguo/Scripts/Data/Generated/PortraitData.g.cs：
     PortraitData.Entries   = { 姓名, 条目 JSON, … }（插入顺序，字段一个不少）
     PortraitData.WorldHand = 有手工设定的世界武将名（tests/world-portraits.html 用）
     PortraitData.Count / Hash = 条目数与校验哈希（FNV-1a 32，见下）；C# 测试据此确认数据完整
   第三版：世界剧本新增人物（天竺 india、非洲 africa、毛里 moor 等）的手工设定由 portrait-data.js 的第三版一节合并，
   照常导出（2026-10：502 条，其中有手工设定的世界武将 159 人）。
   无依赖，Node 14+。数据有变时重新运行即可。
   ========================================================================== */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const WEB = path.resolve(__dirname, '..');
const CHECK = process.argv.includes('--check');
const OUT = process.argv.slice(2).find(a => a !== '--check') || path.resolve(WEB, '../sanguozhi2-unity/Assets/Sanguo/Scripts/Data/Generated/PortraitData.g.cs');

// 在沙箱里按游戏顺序载入（不碰 DOM）
const sandbox = { console };
sandbox.window = sandbox;
vm.createContext(sandbox);
for (const f of ['core.js', 'data.js', 'world-data.js', 'portrait-data.js']) {
  vm.runInContext(fs.readFileSync(path.join(WEB, 'js', f), 'utf8'), sandbox, { filename: f });
}
const PD = sandbox.SG.PortraitData;
const names = PD.names();

// 规范 JSON：键按插入顺序；数值用 JS 的格式（与 C# JObj.ToJson 一致）
function canon(v) {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') { if (!isFinite(v)) throw new Error('非有限数值'); return String(v); }
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'string') return JSON.stringify(v);
  if (Array.isArray(v)) return '[' + v.map(canon).join(',') + ']';
  if (typeof v === 'object') {
    const parts = [];
    for (const k of Object.keys(v)) { if (v[k] === undefined) continue; parts.push(JSON.stringify(k) + ':' + canon(v[k])); }
    return '{' + parts.join(',') + '}';
  }
  throw new Error('无法导出的值：' + typeof v);
}
// FNV-1a 32（按 UTF-16 码元），对 "姓名\u0001JSON\u0002" 逐条累计
function fnv(h, s) {
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619) >>> 0; }
  return h >>> 0;
}
const cs = s => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n') + '"';

let hash = 2166136261 >>> 0;
const lines = [];
for (const n of names) {
  const j = canon(PD.get(n));
  hash = fnv(hash, n + '\u0001' + j + '\u0002');
  lines.push(`            ${cs(n)}, ${cs(j)},`);
}
const hand = (PD.worldHand || []).filter(n => PD.get(n));

const src = `// <auto-generated>
// 自动生成，勿手改：由 sanguozhi2-web/tools/export-unity-portraits.js 从 js/portrait-data.js 导出。
// 数据有变时在 sanguozhi2-web 目录运行 node tools/export-unity-portraits.js 重新生成。
// 格式见 js/portrait-data.js 文件头；运行时由 View/Portrait.cs 的 PortraitDataStore 解析。
// </auto-generated>
namespace Sanguo
{
    public static class PortraitData
    {
        public const int Count = ${names.length};
        public const uint Hash = 0x${hash.toString(16).padStart(8, '0')}u;   // FNV-1a 32 over "姓名\\u0001JSON\\u0002"
        // 姓名, 条目 JSON（键按插入顺序）
        public static readonly string[] Entries =
        {
${lines.join('\n')}
        };
        // 有手工设定的世界武将
        public static readonly string[] WorldHand =
        {
            ${hand.map(cs).join(', ')}
        };
    }
}
`;
if (CHECK) {
  const same = fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8') === src;
  console.log(same ? `PortraitData.g.cs 与 js/portrait-data.js 一致（${names.length} 条）` : `PortraitData.g.cs 已过期：请运行 node tools/export-unity-portraits.js`);
  process.exit(same ? 0 : 1);
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, src);
console.log(`PortraitData.g.cs：${names.length} 条（世界手工 ${hand.length}），hash 0x${hash.toString(16).padStart(8, '0')} → ${path.relative(process.cwd(), OUT)}`);
