  const WE_X = LAT_WEST.map(p => p[0]), WE_Y = LAT_WEST.map(p => p[1]);
  function blendT(lon) { return lon <= TRANS_LON0 ? 0 : lon >= TRANS_LON1 ? 1 : (lon - TRANS_LON0) / (TRANS_LON1 - TRANS_LON0); }
