  // 经度分段：[起点经度, 向东每度的地图单位]。中国本部 97°–126°E 每度 5（锚点 100°E → x = 0）。
  // 往西逐级压缩（塔里木 3.8 → 中亚 3.2 → 巴克特里亚 / 印度河 2.7 → 伊朗 2.4 → 中东 2.2 → 欧洲 2.0），
  // 往东朝鲜 4.4、西日本 3.8、东日本 / 北海道 2.6。
  const LON_SEG = [[-10, 2.0], [24, 2.2], [44, 2.4], [60, 2.7], [74, 3.2], [88, 3.8], [97, 5.0], [126, 4.4], [131, 3.8], [138, 2.6], [146, 2.6]];
  const LON_BP = [], X_BP = [];
  (function () {
    // 以 97°E → x = −15 为锚，向两侧累加
    const n = LON_SEG.length;
    const k97 = LON_SEG.findIndex(s => s[0] === 97);
    for (let i = 0; i < n; i++) LON_BP.push(LON_SEG[i][0]);
    X_BP.length = n;
    X_BP[k97] = -15;
    for (let i = k97 + 1; i < n; i++) X_BP[i] = X_BP[i - 1] + (LON_BP[i] - LON_BP[i - 1]) * LON_SEG[i - 1][1];
    for (let i = k97 - 1; i >= 0; i--) X_BP[i] = X_BP[i + 1] - (LON_BP[i + 1] - LON_BP[i]) * LON_SEG[i][1];
  })();
  const SLOPE_W = LON_SEG[0][1], SLOPE_E = LON_SEG[LON_SEG.length - 1][1];

  // 分段线性函数（断点升序，两端按端段斜率外推）
  function pl(bx, by, v) {
    const n = bx.length;
    if (v <= bx[0]) return by[0] + (v - bx[0]) * (by[1] - by[0]) / (bx[1] - bx[0]);
    if (v >= bx[n - 1]) return by[n - 1] + (v - bx[n - 1]) * (by[n - 1] - by[n - 2]) / (bx[n - 1] - bx[n - 2]);
    let lo = 0, hi = n - 1;
    while (hi - lo > 1) { const m = (lo + hi) >> 1; if (bx[m] <= v) lo = m; else hi = m; }
    return by[lo] + (v - bx[lo]) * (by[hi] - by[lo]) / (bx[hi] - bx[lo]);
  }
  function lonToX(lon) {
    if (lon <= LON_BP[0]) return X_BP[0] + (lon - LON_BP[0]) * SLOPE_W;
    const n = LON_BP.length;
    if (lon >= LON_BP[n - 1]) return X_BP[n - 1] + (lon - LON_BP[n - 1]) * SLOPE_E;
    return pl(LON_BP, X_BP, lon);
  }
  function xToLon(x) {
    if (x <= X_BP[0]) return LON_BP[0] + (x - X_BP[0]) / SLOPE_W;
    const n = X_BP.length;
    if (x >= X_BP[n - 1]) return LON_BP[n - 1] + (x - X_BP[n - 1]) / SLOPE_E;
    return pl(X_BP, LON_BP, x);
  }

  // 纬度剖面：[纬度, y] 断点（两端外推）。
  // 中国剖面：18°–42°N 每度 5.6（23°N → y = 0）；以北 4.2、50°N 以北 3.0；以南每度 4.0。
  const LAT_CHINA = [[-10, -140], [0, -100], [18, -28], [42, 106.4], [50, 140], [60, 170], [80, 230]];
  // 西方剖面（地中海、中东、欧洲、北非）：每度 3.6，30°N 与中国剖面同高（y = 39.2），
  // 东经 62°–97° 之间（伊朗东部、中亚、印度、塔里木）两剖面线性过渡。
  const LAT_WEST = [[-10, -104.8], [80, 219.2]];
  const TRANS_LON0 = 62, TRANS_LON1 = 97;
  // 两剖面合并后的断点（逆变换用）
  const LAT_BP = Array.from(new Set(LAT_CHINA.map(p => p[0]).concat(LAT_WEST.map(p => p[0])))).sort((a, b) => a - b);
