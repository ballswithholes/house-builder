  // 长边按 ≤ 1° 细分后再投影：投影非线性，长边若只投影端点会偏离真实位置（主要是图外的闭合边）
  function projRingDense(pts, maxDeg) {
    const dense = [];
    const n = pts.length >> 1;
    for (let i = 0; i < n; i++) {
      const a0 = pts[2 * i], a1 = pts[2 * i + 1], j = (i + 1) % n, b0 = pts[2 * j], b1 = pts[2 * j + 1];
      const k = Math.max(1, Math.ceil(Math.max(Math.abs(b0 - a0), Math.abs(b1 - a1)) / maxDeg));
      for (let s = 0; s < k; s++) dense.push(a0 + (b0 - a0) * s / k, a1 + (b1 - a1) * s / k);
    }
    return projRing(dense);
  }
