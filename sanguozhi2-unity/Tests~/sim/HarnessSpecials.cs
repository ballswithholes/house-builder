    // 未拆分的单挑（第一版的写法，数值与 JS 相同）：与拆分后的 Duel() 在相同随机数下结果必须完全一致
    static DuelResult DuelV1(BattleModel M, BUnit a, BUnit b)
    {
        var r = new DuelResult();
        r.accepted = b.gen.war >= a.gen.war - 8 || R.value < 0.25f || (b.commander && R.value < 0.4f);
        if (!r.accepted) { b.morale = Math.Max(0, b.morale - 12); a.morale = Math.Min(100, a.morale + 8); return r; }
        int hpA = 100, hpB = 100;
        for (int i = 0; i < 30 && hpA > 0 && hpB > 0; i++)
        {
            int who = R.value < (double)a.gen.war / (a.gen.war + b.gen.war) ? 0 : 1;
            var striker = who == 0 ? a : b;
            int dmg = (int)Math.Round(R.Range(6, 16) * (0.6 + striker.gen.war / 120.0));
            if (who == 0) hpB = Math.Max(0, hpB - dmg); else hpA = Math.Max(0, hpA - dmg);
            r.rounds.Add(new DuelRound { who = who, dmg = dmg, hpA = hpA, hpB = hpB });
        }
        r.winner = hpA >= hpB ? 0 : 1;
        var loser = r.winner == 0 ? b : a; var winner = r.winner == 0 ? a : b;
        loser.Troops = 0; loser.alive = false; M.setup.routed.Add(loser.gen.id);
        foreach (var o in M.Alive(loser.side)) o.morale = Math.Max(0, o.morale - 8);
        winner.morale = Math.Min(100, winner.morale + 15);
        M.CheckEnd();
        return r;
    }
    static void DuelSplit()
    {
        int n = 0;
        for (int seed = 1; seed <= 60; seed++)
        {
            var pr = Sim.Pairs[seed % Sim.Pairs.Length];
            var snap = new List<string>();
            for (int v = 0; v <= 1; v++)
            {
                R.InitState(seed * 31);
                var g = GameState.Current = GameState.NewGame("cao");
                var src = g.CityByKey(pr[0]); var tgt = g.CityByKey(pr[1]);
                var s = Conquest.Prepare(src.owner, src, tgt, g.OfficersIn(src).Where(x => x.troops > 0).Take(5).ToList(), 3000, 0);
                var M = new BattleModel(s);
                var a = M.units[seed % M.Alive(0).Count()]; var b = M.Alive(1).ToList()[seed % M.Alive(1).Count()];
                var r = v == 0 ? DuelV1(M, a, b) : M.Duel(a, b);
                snap.Add($"{r.accepted}|{r.winner}|{string.Join(";", r.rounds.Select(q => q.who + "," + q.dmg + "," + q.hpA + "," + q.hpB))}|next {R.NextDouble():R}|{string.Join(";", M.units.Select(u => u.Troops + "," + u.morale + "," + u.alive))}|{M.result}|{string.Join(",", s.routed)}");
            }
            if (snap[0] != snap[1]) throw new Exception("duel differs at seed " + seed + "\n" + snap[0] + "\n" + snap[1]);
            n++;
        }
        // DuelAccepts + DuelFinish 组合与 Duel() 的后果一致
        R.InitState(5);
        var g2 = GameState.Current = GameState.NewGame("cao");
        var src2 = g2.CityByKey("chenliu"); var tgt2 = g2.CityByKey("luoyang");
        var s2 = Conquest.Prepare(src2.owner, src2, tgt2, g2.OfficersIn(src2).Where(x => x.troops > 0).Take(5).ToList(), 3000, 0);
        var M2 = new BattleModel(s2);
        var a2 = M2.Alive(0).ToList()[1]; var b2 = M2.Alive(1).ToList()[1];
        if (M2.DuelAccepts(a2, b2) != true && b2.gen.war >= a2.gen.war - 8) throw new Exception("DuelAccepts should accept equal opponents");
        var fin = M2.DuelFinish(a2, b2, true, new List<DuelRound> { new DuelRound { who = 0, dmg = 100, hpA = 100, hpB = 0 } });
        if (b2.alive || !a2.alive || fin.winner != 0 || !s2.routed.Contains(b2.gen.id)) throw new Exception("DuelFinish did not resolve the duel");
        Console.WriteLine($"duel split OK ({n} seeds identical to v1)");
    }
