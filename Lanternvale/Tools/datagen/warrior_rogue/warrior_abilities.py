def stance(id_, name, icon, lvl, aura_id, desc, prio):
    return ab(id_, name, icon, desc, ranks=[lvl], time="OffGcd", cooldown=1, cooldownGroup="warrior_stance",
              target="Self", tags=["Stance"],
              effects=[E("Special", target="Self", special="WarriorStanceSwap"), E("ApplyAura", target="Self", aura=aura_id)],
              aiHint="Buff", aiPriority=prio)

def rage(n, consume_all=False):
    c = {"type": "Rage", "amount": n}
    if consume_all:
        c["consumeAll"] = True
    return c

